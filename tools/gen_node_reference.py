"""Generate docs/node-reference.md from the core's op metadata."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "app"))
from vertexcomp import _vccore as vc  # noqa: E402

NOTES = {
    "Roto": "Shapes are edited in the viewer when the node is selected (toolbar in the properties panel): "
            "Bezier (click, drag for tangents, click the first point or Enter to close), rectangle, ellipse, "
            "select/transform with a bounding-box gizmo for several points, Ctrl+click on a curve to insert a point, "
            "Delete to remove, arrows to nudge (Shift x10), point-feather tool. Each shape has blend mode, opacity, "
            "invert, feather (signed distance falloff, smooth or linear) plus per-point feather, edge blur, motion "
            "blur samples/shutter and its own animated transform. Auto-key off: editing a frame without a key "
            "offsets all keys; auto-key on: edits create a key at the current frame.",
    "Read": "Sequences are detected from any file of the sequence. Movies (MOV/MP4/MKV/AVI) decode through "
            "FFmpeg (imageio-ffmpeg); file frames are 0-based, `frame offset` maps them onto the timeline. "
            "TIFF and DPX are not supported by the built-in readers.",
    "Write": "Image sequences: EXR (half/float, ZIP/ZIPS/PIZ/none, data window = bbox, string metadata kept), "
             "PNG 8/16, JPG, TGA, BMP, HDR. Movies: MP4/MOV through FFmpeg (H.264, ProRes 422 HQ, MJPEG). Renders "
             "run in the background from the Render button, Render menu (F7) or `vertexcomp-render`.",
    "Merge": "Inputs B (background), A (foreground), mask. Premultiplied maths: over = A + B(1-a). The photographic "
             "modes (screen, overlay, soft/hard-light, dodge, burn) combine alpha as a + b - ab.",
}


def main():
    out = ["# Node reference", "", "Generated by `tools/gen_node_reference.py` from the core metadata.", "",
           "Common conventions: `channels` selects channels or a layer to process (`rgba`, `rgb`, `alpha`, a layer "
           "name such as `diffuse`, a channel such as `depth.Z`, or a comma separated list). Nodes with a `mask` "
           "input blend their result with `mix` x mask. `(un)premult by alpha` divides colour by rgba.alpha around "
           "the operation (pixels with alpha <= 1e-6 are left alone). Any numeric knob can be keyframed or driven by "
           "an expression (`frame`, other knobs as `knob`, `Node.knob`, `Node.knob.x`).", ""]
    cats = {}
    for o in vc.op_types():
        cats.setdefault(o["category"], []).append(o)
    for cat in sorted(cats):
        out += [f"## {cat}", ""]
        for o in sorted(cats[cat], key=lambda o: o["type"]):
            out += [f"### {o['type']}", "", o["help"], ""]
            if o["type"] in NOTES:
                out += [NOTES[o["type"]], ""]
            if o["inputs"]:
                out += ["Inputs: " + ", ".join(f"`{i or 'input'}`" for i in o["inputs"]), ""]
            out += ["| knob | type | default | notes |", "|---|---|---|---|"]
            for k in o["knobs"]:
                d = k["sdefault"] if k["type"] in ("string", "file", "channel", "channels", "enum", "text") else \
                    ", ".join(f"{v:g}" for v in k["default"])
                if k["type"] == "enum":
                    d = f"{d} ({' / '.join(k['options'])})"
                out.append(f"| `{k['name']}` | {k['type']} | {d} | {k['tooltip']} |")
            out.append("")
    path = os.path.join(os.path.dirname(__file__), "..", "docs", "node-reference.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(path)


if __name__ == "__main__":
    main()
